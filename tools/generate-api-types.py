"""Generate TypeScript DTOs from the application's OpenAPI components, without starting it."""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))


def ts_type(schema):
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    if "enum" in schema:
        return " | ".join(json.dumps(item, ensure_ascii=False) for item in schema["enum"])
    for key, joiner in (("anyOf", " | "), ("oneOf", " | "), ("allOf", " & ")):
        if key in schema:
            return "(" + joiner.join(ts_type(item) for item in schema[key]) + ")"
    kind = schema.get("type")
    if isinstance(kind, list):
        return " | ".join(ts_type({**schema, "type": item}) for item in kind)
    if kind == "null":
        return "null"
    if kind in {"integer", "number"}:
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "string":
        return "string"
    if kind == "array":
        return f"Array<{ts_type(schema.get('items', {}))}>"
    if kind == "object" or "properties" in schema:
        properties = schema.get("properties", {})
        if not properties:
            additional = schema.get("additionalProperties", {})
            return "Record<string, " + (ts_type(additional) if isinstance(additional, dict) else "unknown") + ">"
        required = set(schema.get("required", []))
        fields = [f"  {json.dumps(name)}{'' if name in required else '?'}: {ts_type(value)}"
                  for name, value in properties.items()]
        if schema.get("additionalProperties") is True:
            fields.append("  [key: string]: unknown")
        return "{\n" + "\n".join(fields) + "\n}"
    return "unknown"


def render():
    from site_hub.main import create_app
    schemas = create_app(start_background=False).openapi()["components"]["schemas"]
    return ("// Generated by tools/generate-api-types.py from FastAPI OpenAPI. Do not edit.\n"
            + "// Regenerate after API model changes; --check fails on drift.\n\n"
            + "\n\n".join(f"export type {name} = {ts_type(schema)}" for name, schema in sorted(schemas.items()))
            + "\n")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    target = ROOT / "frontend/src/api/generated.ts"
    value = render()
    if options.check:
        if not target.exists() or target.read_text(encoding="utf-8") != value:
            raise SystemExit("API types are stale. Run tools/generate-api-types.py.")
        print("OpenAPI TypeScript DTOs are up to date.")
    else:
        target.write_text(value, encoding="utf-8")
        print(f"Generated {target.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
